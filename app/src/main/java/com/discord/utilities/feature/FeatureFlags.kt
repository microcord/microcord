    fun voiceMessagesEnabled() = enabled(ClientSettings.voiceMessages)
    fun setVoiceMessagesEnabled(enabled: Boolean) = setEnabled(ClientSettings.voiceMessages, enabled)
    fun tapTapEnabled() = enabled(ClientSettings.tapTap)
    fun setTapTapEnabled(enabled: Boolean) = setEnabled(ClientSettings.tapTap, enabled)
    fun tapTapReplyOwnEnabled() = enabled(ClientSettings.tapTapReplyOwn)
    fun setTapTapReplyOwnEnabled(enabled: Boolean) = setEnabled(ClientSettings.tapTapReplyOwn, enabled)
    fun fetchUncachedUsersEnabled() = enabled(ClientSettings.fetchUncachedUsers)
    fun setFetchUncachedUsersEnabled(enabled: Boolean) = setEnabled(ClientSettings.fetchUncachedUsers, enabled)
    fun viewProfileImagesEnabled() = enabled(ClientSettings.viewProfileImages)
    fun setViewProfileImagesEnabled(enabled: Boolean) = setEnabled(ClientSettings.viewProfileImages, enabled)
    fun disableServerProfilesEnabled() = enabled(ClientSettings.disableServerProfiles)
    fun setDisableServerProfilesEnabled(enabled: Boolean) = setEnabled(ClientSettings.disableServerProfiles, enabled)
    fun chatboxCustomizationsEnabled() = enabled(ClientSettings.chatboxCustomizations)
    fun setChatboxCustomizationsEnabled(enabled: Boolean) = setEnabled(ClientSettings.chatboxCustomizations, enabled)
    fun headerCustomizationsEnabled() = enabled(ClientSettings.headerCustomizations)
    fun setHeaderCustomizationsEnabled(enabled: Boolean) = setEnabled(ClientSettings.headerCustomizations, enabled)
    fun typingUserAvatarsEnabled() = enabled(ClientSettings.typingUserAvatars)
    fun setTypingUserAvatarsEnabled(enabled: Boolean) = setEnabled(ClientSettings.typingUserAvatars, enabled)
    fun chatHeaderStatusIndicatorsEnabled() = enabled(ClientSettings.chatHeaderStatusIndicators)
    fun setChatHeaderStatusIndicatorsEnabled(enabled: Boolean) = setEnabled(ClientSettings.chatHeaderStatusIndicators, enabled)
    fun moreGifProvidersEnabled() = enabled(ClientSettings.moreGifProviders)
    fun setMoreGifProvidersEnabled(enabled: Boolean) = setEnabled(ClientSettings.moreGifProviders, enabled)
    fun gifUrlToInputEnabled() = enabled(ClientSettings.gifUrlToInput)
    fun setGifUrlToInputEnabled(enabled: Boolean) = setEnabled(ClientSettings.gifUrlToInput, enabled)
    fun quickMessageActionsEnabled() = enabled(ClientSettings.quickMessageActions)
    fun setQuickMessageActionsEnabled(enabled: Boolean) = setEnabled(ClientSettings.quickMessageActions, enabled)
    fun messageCustomizationsEnabled() = enabled(ClientSettings.messageCustomizations)
    fun setMessageCustomizationsEnabled(enabled: Boolean) = setEnabled(ClientSettings.messageCustomizations, enabled)
    fun messageLimitCounterEnabled() = enabled(ClientSettings.messageLimitCounter)
    fun setMessageLimitCounterEnabled(enabled: Boolean) = setEnabled(ClientSettings.messageLimitCounter, enabled)
    fun avatarDecorationsEnabled() = enabled(ClientSettings.avatarDecorations)
    fun setAvatarDecorationsEnabled(enabled: Boolean) = setEnabled(ClientSettings.avatarDecorations, enabled)
    fun nameplatesEnabled() = enabled(ClientSettings.nameplates)
    fun setNameplatesEnabled(enabled: Boolean) = setEnabled(ClientSettings.nameplates, enabled)
    fun profileEffectsEnabled() = enabled(ClientSettings.profileEffects)
    fun setProfileEffectsEnabled(enabled: Boolean) = setEnabled(ClientSettings.profileEffects, enabled)
    fun profileFramesEnabled() = enabled(ClientSettings.profileFrames)
    fun setProfileFramesEnabled(enabled: Boolean) = setEnabled(ClientSettings.profileFrames, enabled)
    fun nitroSpoofEnabled() = enabled(ClientSettings.nitroSpoof)
    fun setNitroSpoofEnabled(enabled: Boolean) = setEnabled(ClientSettings.nitroSpoof, enabled)
    fun silentTypingEnabled() = enabled(ClientSettings.silentTyping)
    fun setSilentTypingEnabled(enabled: Boolean) = setEnabled(ClientSettings.silentTyping, enabled)
    fun smoothKeyboardEnabled() = enabled(ClientSettings.smoothKeyboard)
    fun setSmoothKeyboardEnabled(enabled: Boolean) = setEnabled(ClientSettings.smoothKeyboard, enabled)
    fun maximumRefreshRateEnabled() = enabled(ClientSettings.maximumRefreshRate)
    fun setMaximumRefreshRateEnabled(enabled: Boolean) = setEnabled(ClientSettings.maximumRefreshRate, enabled)
    fun cloudSettingsBackupEnabled() = enabled(ClientSettings.cloudSettingsBackup)
    fun setCloudSettingsBackupEnabled(enabled: Boolean) = setEnabled(ClientSettings.cloudSettingsBackup, enabled)

    private fun enabled(setting: ClientSettings.Setting<Boolean>) =
        SharedPreferencesProvider.getOrNull()?.let(setting::get) ?: setting.default

    private fun setEnabled(setting: ClientSettings.Setting<Boolean>, enabled: Boolean) =
        setting.set(SharedPreferencesProvider.get(), enabled)
}
