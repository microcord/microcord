"""Regenerates .github/mirror-exclude.txt: what the public GitHub mirror leaves out.

The mirror publishes the project's own code, not Discord's files. Out go:
- Discord's native libraries, voice models and assets.
- Every resource file recovered from the APK.
- Discord's Firebase client config, and the signing key.
- Build output and local junk that was committed at some point.

Every path in the repository's history is classified, not only the current tree, because the
mirror rewrites the whole history.

A resource counts as Discord's when Discord 126.21 ships a file of the same name and type, or when
it is a binary (image, font, sound, animation). Binaries are matched by a rule rather than listed,
so new ones are caught automatically. Rerun this after importing resources from a newer Discord
build, so new recovered XML is listed too.

Usage: python scripts/mirror_exclude.py <reference res dir> > .github/mirror-exclude.txt
The reference res dir is the read-only JADX export, e.g. ../discord-jadx/app/src/main/res.
"""
import os
import subprocess
import sys

RES = "app/src/main/res/"

# Literal paths and directories (a trailing slash matches everything below).
FIXED = [
    ("Discord's native libraries and voice models", [
        "app/src/main/jniLibs/",
        "app/src/main/assets/",
        "third_party/webrtc-discord-126.21/",
    ]),
    ("Discord's Firebase client config, and the APK signing key: with it anyone could sign an update", [
        "app/google-services.json",
        "app/manticord-dev.keystore",
    ]),
    ("Compiled Discord drawables used as test fixtures", [
        "app/src/test/resources/fixtures/theme/",
    ]),
    ("This repository's own CI and mirror setup; GHES workflows cannot run on github.com", [
        ".github/",
    ]),
    ("Build output, local logs and scratch files committed at some point", [
        ".buildlock/",
        ".kotlin/",
        ".codegraph/",
        "plugin-api/build/",
        "sample-plugin/build/",
        "app/src/main/bash.exe.stackdump",
        "cp.txt",
        "extract_cp.py",
    ]),
]

# Every binary resource except the launcher icons.
BINARY_RESOURCES = r"regex:^app/src/main/res/(?!mipmap-)[^/]+/[^/]+\.(png|webp|jpe?g|gif|json|mp3|ogg|wav|ttf|otf)$"
IDE_FILES = r"regex:^\.idea/(?!codeStyles/)"


def history_paths():
    out = subprocess.run(
        ["git", "log", "--all", "--name-only", "--format="], capture_output=True, text=True, check=True,
    ).stdout
    return sorted({line for line in out.splitlines() if line})


def main(reference_res):
    # filter-repo would read a carriage return as part of the path.
    sys.stdout.reconfigure(newline="\n")
    shipped = {
        (directory.split("-")[0], name)
        for directory in os.listdir(reference_res)
        for name in os.listdir(os.path.join(reference_res, directory))
    }
    recovered_xml = []
    for path in history_paths():
        parts = path[len(RES):].split("/")
        if path.startswith(RES) and len(parts) == 2 and path.endswith(".xml"):
            if (parts[0].split("-")[0], parts[1]) in shipped:
                recovered_xml.append(path)

    print("# What the public GitHub mirror leaves out. Generated by scripts/mirror_exclude.py; do not edit.")
    print("# Read by `git filter-repo --invert-paths --paths-from-file` in .github/workflows/mirror.yml.")
    for title, paths in FIXED:
        print()
        print(f"# {title}")
        for path in paths:
            print(path)
    print()
    print("# IDE settings other than the shared code style")
    print(IDE_FILES)
    print()
    print("# Images, fonts, sounds and animations recovered from Discord (launcher icons stay)")
    print(BINARY_RESOURCES)
    print()
    print(f"# Resource XML recovered from Discord 126.21 ({len(recovered_xml)} files)")
    for path in recovered_xml:
        print(path)


if __name__ == "__main__":
    main(sys.argv[1])
