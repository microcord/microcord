class CacheFormatProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment) =
        CacheFormatProcessor(environment.codeGenerator, environment.logger)
}

/**
 * Generates `<Class>CacheFormat` for every `@CachedFormat` class: plain `write`/`read` functions
 * over Kryo's `Output`/`Input` that rebuild the object through its primary constructor, plus a
 * `LAYOUT_HASH` a cache stores in its header so a model change discards the old file.
 *
 * Each constructor property is written in declaration order, with no tags:
 * - `Int`/`Long`/`Short` as varints, other primitives raw; nullable ones behind a present flag.
 * - `String` through Kryo's string encoding, which carries null itself.
 * - enums as ordinal + 1, 0 for null.
 * - another `@CachedFormat` class through its generated codec, behind a present flag; a sealed one
 *   by subclass index, its `object` subclasses read back as the real singleton.
 * - `List`/`Set`/`Collection` of any of the above as size + 1 (0 for null) and the elements.
 * - anything else through `kryo.writeClassAndObject`, for rare nested models.
 *
 * Gson can leave Kotlin non-null fields null, so every reference value tolerates null on write.
 * On read, a null in a non-null field becomes "", the enum's first constant or an empty
 * collection, and for a nested model the read fails, which makes the persister discard the cache.
 *
 * [LAYOUT_HASH] covers every written field's name and type, enum constants, nested codecs, and the
 * fields of the classes handed to Kryo (as far as they are source in this module).
 */
class CacheFormatProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {
    override fun process(resolver: Resolver): List<KSAnnotated> {
        resolver.getSymbolsWithAnnotation(ANNOTATION)
            .filterIsInstance<KSClassDeclaration>()
            .forEach { declaration -> runCatching { generate(declaration) }.onFailure { logger.error("$it", declaration) } }
        return emptyList()
    }

    private fun generate(declaration: KSClassDeclaration) {
        val files = HashSet<KSFile>()
        val signature = StringBuilder().also { signature(declaration, it, HashSet(), files) }.toString()
        val name = formatName(declaration)
        val packageName = declaration.packageName.asString()
        val code = StringBuilder()
        code.appendLine("// Generated by :cache-codegen from ${declaration.qualifiedName!!.asString()}. Do not edit.")
        code.appendLine("@file:Suppress(\"UNCHECKED_CAST\", \"RedundantVisibilityModifier\", \"unused\", \"NAME_SHADOWING\", \"USELESS_CAST\")")
        code.appendLine()
        code.appendLine("package $packageName")
        code.appendLine()
        code.appendLine("internal object $name {")
        code.appendLine("    const val LAYOUT_HASH: Int = ${signature.hashCode()}")
        if (Modifier.SEALED in declaration.modifiers) sealedBody(declaration, code) else classBody(declaration, code)
        code.appendLine("}")
        files += listOfNotNull(declaration.containingFile)
        codeGenerator.createNewFile(Dependencies(true, *files.toTypedArray()), packageName, name)
            .bufferedWriter().use { it.write(code.toString()) }
    }

    // region Code

    private fun classBody(declaration: KSClassDeclaration, code: StringBuilder) {
        val type = declaration.qualifiedName!!.asString()
        val parameters = persistedParameters(declaration)
        val persisted = parameters.mapTo(HashSet()) { it.name!!.asString() }
        val helpers = StringBuilder()
        code.appendLine()
        code.appendLine("    fun write(kryo: com.esotericsoftware.kryo.Kryo, output: com.esotericsoftware.kryo.io.Output, value: $type) {")
        parameters.forEachIndexed { index, parameter ->
            writeField(parameter, "value.${parameter.name!!.asString()}", "f$index", code)
        }
        code.appendLine("    }")
        code.appendLine()
        code.appendLine("    fun read(kryo: com.esotericsoftware.kryo.Kryo, input: com.esotericsoftware.kryo.io.Input): $type = $type(")
        declaration.primaryConstructor!!.parameters.forEach { parameter ->
            val name = parameter.name!!.asString()
            if (name in persisted) {
                code.appendLine("        $name = ${readField(parameter, helpers)},")
            } else if (!parameter.hasDefault) {
                code.appendLine("        $name = null,")
            }
        }
        code.appendLine("    )")
        code.append(helpers)
    }

    private fun sealedBody(declaration: KSClassDeclaration, code: StringBuilder) {
        val type = declaration.qualifiedName!!.asString()
        val subclasses = declaration.getSealedSubclasses().sortedBy { it.qualifiedName!!.asString() }.toList()
        code.appendLine()
        code.appendLine("    fun write(kryo: com.esotericsoftware.kryo.Kryo, output: com.esotericsoftware.kryo.io.Output, value: $type) {")
        code.appendLine("        when (value) {")
        subclasses.forEachIndexed { index, subclass ->
            val sub = subclass.qualifiedName!!.asString()
            if (subclass.classKind == ClassKind.OBJECT) {
                code.appendLine("            is $sub -> output.writeVarInt($index, true)")
            } else {
                requireCodec(subclass)
                code.appendLine("            is $sub -> { output.writeVarInt($index, true); ${codecName(subclass)}.write(kryo, output, value) }")
            }
        }
        code.appendLine("        }")
        code.appendLine("    }")
        code.appendLine()
        code.appendLine("    fun read(kryo: com.esotericsoftware.kryo.Kryo, input: com.esotericsoftware.kryo.io.Input): $type =")
        code.appendLine("        when (val index = input.readVarInt(true)) {")
        subclasses.forEachIndexed { index, subclass ->
            val sub = subclass.qualifiedName!!.asString()
            code.appendLine(
                if (subclass.classKind == ClassKind.OBJECT) "            $index -> $sub"
                else "            $index -> ${codecName(subclass)}.read(kryo, input)",
            )
        }
        code.appendLine("            else -> throw com.esotericsoftware.kryo.KryoException(\"Unknown $type subclass \$index\")")
        code.appendLine("        }")
    }

    private fun writeField(parameter: KSValueParameter, expression: String, local: String, code: StringBuilder) {
        val type = parameter.type.resolve().expanded()
        val rendered = render(type.makeNullable())
        when (val kind = kindOf(type)) {
            is Kind.Primitive -> if (type.isMarkedNullable) {
                code.appendLine("        val $local: $rendered = $expression")
                code.appendLine("        output.writeBoolean($local != null)")
                code.appendLine("        if ($local != null) ${kind.write(local)}")
            } else {
                code.appendLine("        ${kind.write(expression)}")
            }
            Kind.Str -> code.appendLine("        output.writeString($expression)")
            is Kind.Enum -> {
                code.appendLine("        val $local: $rendered = $expression")
                code.appendLine("        output.writeVarInt($local?.ordinal?.plus(1) ?: 0, true)")
            }
            is Kind.Codec -> {
                code.appendLine("        val $local: $rendered = $expression")
                code.appendLine("        output.writeBoolean($local != null)")
                code.appendLine("        if ($local != null) ${codecName(kind.declaration)}.write(kryo, output, $local)")
            }
            is Kind.Collection -> {
                val element = render(kind.element.makeNullable())
                code.appendLine("        val $local: kotlin.collections.Collection<$element>? = $expression")
                code.appendLine("        output.writeVarInt($local?.size?.plus(1) ?: 0, true)")
                code.appendLine("        if ($local != null) for (element in $local) ${writeElement(kind)}")
            }
            Kind.Kryo -> code.appendLine("        kryo.writeClassAndObject(output, $expression)")
        }
    }

    private fun writeElement(kind: Kind.Collection): String = when (val element = kind.elementKind) {
        is Kind.Primitive -> element.write("element!!")
        Kind.Str -> "output.writeString(element)"
        is Kind.Enum -> "output.writeVarInt(element?.ordinal?.plus(1) ?: 0, true)"
        is Kind.Codec -> "${codecName(element.declaration)}.write(kryo, output, element!!)"
        else -> error("unreachable")
    }

    private fun readField(parameter: KSValueParameter, helpers: StringBuilder): String {
        val type = parameter.type.resolve().expanded()
        val nullable = type.isMarkedNullable
        return when (val kind = kindOf(type)) {
            is Kind.Primitive -> if (nullable) "if (input.readBoolean()) ${kind.read} else null" else kind.read
            Kind.Str -> if (nullable) "input.readString()" else "(input.readString() ?: \"\")"
            is Kind.Enum -> readEnum(kind.declaration, nullable)
            is Kind.Codec -> {
                val read = "${codecName(kind.declaration)}.read(kryo, input)"
                if (nullable) "if (input.readBoolean()) $read else null"
                else "if (input.readBoolean()) $read else throw com.esotericsoftware.kryo.KryoException(\"null ${parameter.name!!.asString()}\")"
            }
            is Kind.Collection -> {
                val helper = "read_${parameter.name!!.asString()}"
                val element = render(kind.element.makeNullable())
                val container = if (kind.isSet) "java.util.HashSet<$element>(size * 2)" else "java.util.ArrayList<$element>(size)"
                val empty = if (kind.isSet) "java.util.HashSet()" else "java.util.ArrayList()"
                helpers.appendLine()
                helpers.appendLine("    private fun $helper(kryo: com.esotericsoftware.kryo.Kryo, input: com.esotericsoftware.kryo.io.Input): ${render(type)} {")
                helpers.appendLine("        val size = input.readVarInt(true) - 1")
                helpers.appendLine("        if (size < 0) return ${if (nullable) "null" else empty}")
                helpers.appendLine("        val result = $container")
                helpers.appendLine("        repeat(size) { result.add(${readElement(kind)}) }")
                helpers.appendLine("        return result as ${render(type)}")
                helpers.appendLine("    }")
                "$helper(kryo, input)"
            }
            Kind.Kryo -> "(kryo.readClassAndObject(input) as ${render(type)})"
        }
    }

    private fun readElement(kind: Kind.Collection): String = when (val element = kind.elementKind) {
        is Kind.Primitive -> element.read
        Kind.Str -> "input.readString()"
        is Kind.Enum -> readEnum(element.declaration, nullable = true)
        is Kind.Codec -> "${codecName(element.declaration)}.read(kryo, input)"
        else -> error("unreachable")
    }

    private fun readEnum(declaration: KSClassDeclaration, nullable: Boolean): String {
        val type = declaration.qualifiedName!!.asString()
        val absent = if (nullable) "null" else "$type.entries[0]"
        return "input.readVarInt(true).let { if (it == 0) $absent else $type.entries[it - 1] }"
    }

    // endregion

    // region Model

    private sealed interface Kind {
        class Primitive(private val writer: String, val read: String) : Kind {
            fun write(value: String) = writer.replace("#", value)
        }
        data object Str : Kind
        class Enum(val declaration: KSClassDeclaration) : Kind
        class Codec(val declaration: KSClassDeclaration) : Kind
        class Collection(val isSet: Boolean, val element: KSType, val elementKind: Kind) : Kind
        data object Kryo : Kind
    }

    private fun kindOf(type: KSType, allowCollections: Boolean = true): Kind {
        val declaration = type.declaration as? KSClassDeclaration ?: return Kind.Kryo
        val name = declaration.qualifiedName?.asString()
        PRIMITIVES[name]?.let { return it }
        return when {
            name == "kotlin.String" -> Kind.Str
            declaration.classKind == ClassKind.ENUM_CLASS -> Kind.Enum(declaration)
            declaration.isCodec() -> Kind.Codec(declaration)
            allowCollections && name in COLLECTIONS -> {
                val element = type.arguments.single().type?.resolve()?.expanded() ?: return Kind.Kryo
                when (val elementKind = kindOf(element, allowCollections = false)) {
                    is Kind.Primitive, Kind.Str, is Kind.Enum, is Kind.Codec ->
                        Kind.Collection(name == "kotlin.collections.Set", element, elementKind)
                    else -> Kind.Kryo
                }
            }
            else -> Kind.Kryo
        }
    }

    /** Constructor properties that are persisted; transient ones are rebuilt from their default or null. */
    private fun persistedParameters(declaration: KSClassDeclaration): List<KSValueParameter> {
        val constructor = declaration.primaryConstructor
            ?: throw IllegalStateException("@CachedFormat needs a primary constructor")
        val properties = declaration.getAllProperties().associateBy { it.simpleName.asString() }
        val parameters = constructor.parameters.filter { parameter ->
            val name = parameter.name!!.asString()
            check(parameter.isVal || parameter.isVar) { "$name must be a val or var to be cached" }
            val transient = parameter.isTransient() || properties[name]?.isTransient() == true
            if (transient) check(parameter.hasDefault || parameter.type.resolve().isMarkedNullable) {
                "transient $name needs a default or a nullable type, the cache cannot restore it"
            }
            !transient
        }
        val constructorNames = constructor.parameters.mapTo(HashSet()) { it.name!!.asString() }
        declaration.getDeclaredProperties()
            .filter { it.simpleName.asString() !in constructorNames && it.hasBackingField && it.isMutable && !it.isTransient() }
            .forEach { throw IllegalStateException("${it.simpleName.asString()} is mutable state outside the constructor; the cache would lose it") }
        return parameters
    }

    private fun requireCodec(declaration: KSClassDeclaration) =
        check(declaration.isCodec()) { "${declaration.qualifiedName!!.asString()} needs @CachedFormat too" }

    private fun KSClassDeclaration.isCodec() =
        annotations.any { it.annotationType.resolve().declaration.qualifiedName?.asString() == ANNOTATION }

    private fun KSAnnotated.isTransient() =
        annotations.any { it.annotationType.resolve().declaration.qualifiedName?.asString() == "kotlin.jvm.Transient" }

    private fun KSType.expanded(): KSType {
        val alias = declaration as? KSTypeAlias ?: return this
        val target = alias.type.resolve().expanded()
        return if (isMarkedNullable) target.makeNullable() else target
    }

    private fun render(type: KSType): String {
        val expanded = type.expanded()
        val base = expanded.declaration.qualifiedName!!.asString()
        val arguments = if (expanded.arguments.isEmpty()) "" else expanded.arguments.joinToString(prefix = "<", postfix = ">") { argument ->
            when (argument.variance) {
                Variance.STAR -> "*"
                Variance.COVARIANT -> "out " + render(argument.type!!.resolve())
                Variance.CONTRAVARIANT -> "in " + render(argument.type!!.resolve())
                else -> render(argument.type!!.resolve())
            }
        }
        return base + arguments + if (expanded.isMarkedNullable) "?" else ""
    }

    private fun formatName(declaration: KSClassDeclaration): String {
        val names = generateSequence(declaration) { it.parentDeclaration as? KSClassDeclaration }.map { it.simpleName.asString() }
        return names.toList().reversed().joinToString("_") + "CacheFormat"
    }

    private fun codecName(declaration: KSClassDeclaration) = declaration.packageName.asString() + "." + formatName(declaration)

    // endregion

    // region Layout signature

    private fun signature(declaration: KSClassDeclaration, out: StringBuilder, seen: HashSet<String>, files: HashSet<KSFile>) {
        val name = declaration.qualifiedName!!.asString()
        out.append(name)
        if (!seen.add(name)) return
        declaration.containingFile?.let(files::add)
        when {
            declaration.classKind == ClassKind.ENUM_CLASS ->
                declaration.declarations.filterIsInstance<KSClassDeclaration>()
                    .filter { it.classKind == ClassKind.ENUM_ENTRY }
                    .joinTo(out, ",", "[", "]") { it.simpleName.asString() }
            declaration.isCodec() && Modifier.SEALED in declaration.modifiers -> {
                out.append("sealed{")
                declaration.getSealedSubclasses().sortedBy { it.qualifiedName!!.asString() }
                    .forEach { signature(it, out, seen, files); out.append(';') }
                out.append('}')
            }
            declaration.isCodec() && declaration.classKind != ClassKind.OBJECT -> {
                out.append('(')
                persistedParameters(declaration).forEach { parameter ->
                    out.append(parameter.name!!.asString()).append(':')
                    typeSignature(parameter.type.resolve().expanded(), out, seen, files)
                    out.append(';')
                }
                out.append(')')
            }
            // Handed to Kryo: its field serializer writes every field with a backing field.
            declaration.origin == Origin.KOTLIN || declaration.origin == Origin.JAVA -> {
                out.append('{')
                declaration.getAllProperties()
                    .filter { it.hasBackingField && !it.isTransient() && Modifier.JAVA_STATIC !in it.modifiers }
                    .forEach { property: KSPropertyDeclaration ->
                        out.append(property.simpleName.asString()).append(':')
                        typeSignature(property.type.resolve().expanded(), out, seen, files)
                        out.append(';')
                    }
                out.append('}')
            }
        }
    }

    private fun typeSignature(type: KSType, out: StringBuilder, seen: HashSet<String>, files: HashSet<KSFile>) {
        val declaration = type.declaration as? KSClassDeclaration
        if (declaration == null) out.append(type.declaration.qualifiedName?.asString()) else signature(declaration, out, seen, files)
        if (type.arguments.isNotEmpty()) {
            out.append('<')
            type.arguments.forEach { argument ->
                argument.type?.resolve()?.expanded()?.let { typeSignature(it, out, seen, files) } ?: out.append('*')
                out.append(',')
            }
            out.append('>')
        }
        if (type.isMarkedNullable) out.append('?')
    }

    // endregion

    companion object {
        const val ANNOTATION = "com.discord.utilities.persister.CachedFormat"

        private val COLLECTIONS = setOf("kotlin.collections.List", "kotlin.collections.Set", "kotlin.collections.Collection")

        private val PRIMITIVES = mapOf(
            "kotlin.Int" to Kind.Primitive("output.writeVarInt(#, true)", "input.readVarInt(true)"),
            "kotlin.Long" to Kind.Primitive("output.writeVarLong(#, true)", "input.readVarLong(true)"),
            "kotlin.Short" to Kind.Primitive("output.writeVarInt((#).toInt(), true)", "input.readVarInt(true).toShort()"),
            "kotlin.Boolean" to Kind.Primitive("output.writeBoolean(#)", "input.readBoolean()"),
            "kotlin.Byte" to Kind.Primitive("output.writeByte(#)", "input.readByte()"),
            "kotlin.Char" to Kind.Primitive("output.writeChar(#)", "input.readChar()"),
            "kotlin.Float" to Kind.Primitive("output.writeFloat(#)", "input.readFloat()"),
            "kotlin.Double" to Kind.Primitive("output.writeDouble(#)", "input.readDouble()"),
        )
    }
}
